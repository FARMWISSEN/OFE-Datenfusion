    def validate_variogram_parameters(self):
        """Validate variogram parameters and update UI state."""
        try:
            nugget = self.doubleSpinBox_nugget.value()
            sill = self.doubleSpinBox_sill.value()
            range_ = self.doubleSpinBox_range.value()
            
            # Warn if parameters might be suboptimal
            warnings = []
            
            if nugget < 0:
                warnings.append("Nugget sollte nicht negativ sein")
            
            if range_ <= 0:
                warnings.append("Range sollte größer als 0 sein")
            
            if sill <= 0:
                warnings.append("Sill sollte größer als 0 sein")
            
            if nugget > sill:
                warnings.append("Nugget sollte nicht größer als Sill sein")
            
            # Show warnings if any
            if warnings:
                warning_text = "\n".join(warnings)
                QgsMessageLog.logMessage(
                    f"Variogram Parameter Warnings:\n{warning_text}",
                    "I-PlugIn",
                    Qgis.Warning
                )
            
        except Exception as e:
            QgsMessageLog.logMessage(
                f"Parameter validation failed: {str(e)}",
                "I-PlugIn",
                Qgis.Critical
            )

    def update_variogram_parameters(self, parameters, point_tab=False):
        """Update variogram parameters in the UI (raster or point tab, strictly separated)."""
        try:
            if not parameters:
                return

            if point_tab:
                # Update only point tab widgets
                self.doubleSpinBox_nugget_point.setValue(parameters.get('nugget', 0.0))
                self.doubleSpinBox_range_point.setValue(parameters.get('range', 100.0))
                self.doubleSpinBox_sill_point.setValue(parameters.get('sill', 1.0))
                # Use a dedicated metrics label for the point tab
                if not hasattr(self, 'metrics_label_points'):
                    parent_widget = self.page_kriging_2 if hasattr(self, 'page_kriging_2') else self
                    self.metrics_label_points = QtWidgets.QLabel(parent_widget)
                    layout = parent_widget.layout()
                    if not layout:
                        layout = QtWidgets.QVBoxLayout(parent_widget)
                        parent_widget.setLayout(layout)
                    layout.addWidget(self.metrics_label_points)
                metrics_label = self.metrics_label_points
            else:
                # Update only raster tab widgets
                self.doubleSpinBox_nugget.setValue(parameters.get('nugget', 0.0))
                self.doubleSpinBox_range.setValue(parameters.get('range', 100.0))
                self.doubleSpinBox_sill.setValue(parameters.get('sill', 1.0))
                # Use a dedicated metrics label for the raster tab
                if not hasattr(self, 'metrics_label_raster'):
                    parent_widget = self.page_kriging if hasattr(self, 'page_kriging') else self
                    self.metrics_label_raster = QtWidgets.QLabel(parent_widget)
                    layout = parent_widget.layout()
                    if not layout:
                        layout = QtWidgets.QVBoxLayout(parent_widget)
                        parent_widget.setLayout(layout)
                    layout.addWidget(self.metrics_label_raster)
                metrics_label = self.metrics_label_raster

            # Update metrics display only in the correct tab
            metrics = parameters.get('metrics', {})
            if metrics:
                metrics_text = (
                    f"<b>Variogramm Metriken:</b><br>"
                    f"RMSE: {metrics.get('rmse', 'N/A'):.3f}<br>"
                    f"R²: {metrics.get('r2', 'N/A'):.3f}"
                )
                metrics_label.setText(metrics_text)
                metrics_label.setVisible(True)
            else:
                metrics_label.setVisible(False)

        except Exception as e:
            QgsMessageLog.logMessage(
                f"Failed to update variogram parameters: {str(e)}",
                "I-PlugIn",
                Qgis.Critical
            )
