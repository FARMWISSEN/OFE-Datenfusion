    def interpolate_points(self):
        """Handle point interpolation button click."""
        try:
            # Validate inputs
            if not self.validate_point_interpolation_inputs():
                return
                
            # Get parameters
            params = self.get_point_interpolation_parameters()
            
            # Save current settings
            self.save_settings()
            
            # Create progress dialog
            progress = QProgressDialog(
                "Punkt-Interpolation läuft...",
                "Abbrechen",
                0,
                0,
                self
            )
            progress.setWindowTitle("I-PlugIn")
            progress.setWindowModality(Qt.WindowModal)
            progress.setMinimumDuration(0)
            progress.setAutoClose(True)
            progress.setAutoReset(True)
            progress.setMinimum(0)
            progress.setMaximum(0)  # Unbestimmter Fortschritt
            
            # Run interpolation
            if self.plugin:
                try:
                    # Show progress dialog
                    progress.show()
                    
                    # Process events to keep UI responsive
                    QCoreApplication.processEvents()
                    
                    # Run interpolation
                    self.plugin.run_point_interpolation(params)
                    
                    # Close progress dialog
                    progress.close()
                    
                    QMessageBox.information(
                        self,
                        "Erfolg",
                        "Punkt-Interpolation erfolgreich abgeschlossen."
                    )
                    
                except Exception as e:
                    progress.close()
                    raise e
                    
                finally:
                    progress.close()
            
        except Exception as e:
            QMessageBox.critical(
                self,
                "Fehler",
                f"Fehler bei der Punkt-Interpolation: {str(e)}"
            )

