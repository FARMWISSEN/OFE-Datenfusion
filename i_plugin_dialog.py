    def load_settings(self):
        """Load saved settings."""
        settings = QSettings()
        
        # Load layer and field selections
        layer_id = settings.value("IPlugIn/input_layer", "")
        if layer_id:
            layer = QgsProject.instance().mapLayer(layer_id)
            if layer:
                self.mMapLayerComboBox.setLayer(layer)
                
        field = settings.value("IPlugIn/input_field", "")
        if field:
            self.mFieldComboBox.setField(field)
            
        boundary_id = settings.value("IPlugIn/boundary_layer", "")
        if boundary_id:
            layer = QgsProject.instance().mapLayer(boundary_id)
            if layer:
                self.mMapLayerComboBox_boundary.setLayer(layer)
                      
        # Load interpolation settings
        self.doubleSpinBox_cellsize.setValue(float(settings.value("IPlugIn/cell_size", 10.0)))
        
        # Load kriging parameters
        try:
            variogram_idx = int(settings.value("IPlugIn/variogram_model", 0))
            if 0 <= variogram_idx < self.comboBox_variogram.count():
                self.comboBox_variogram.setCurrentIndex(variogram_idx)
        except (ValueError, TypeError):
            # If there's an error, just set to first item
            self.comboBox_variogram.setCurrentIndex(0)
            
        self.doubleSpinBox_nugget.setValue(float(settings.value("nugget", 0.0)))
        self.doubleSpinBox_range.setValue(float(settings.value("range", 100.0)))
        self.doubleSpinBox_sill.setValue(float(settings.value("sill", 1.0)))
        self.spinBox_lags.setValue(int(settings.value("lags", 15)))

